# The kind tier's server.conf, as a kustomize patch: the rendered ConfigMap's
# server.conf (one JSON key of one ConfigMap, so a patch replaces it whole) plus the
# `tpm` NodeAttestor block, read from deploy/spire-tpm/server.conf.fragment.hcl so the
# component stays the single source of the plugin's path, checksum and CA directory.
# Run by `make kind-spire-render`; the output is tracked.
#
# Usage: render-server-conf-patch.sh <rendered spire.yaml> <server.conf.fragment.hcl>
set -eu
rendered=$1
fragment=$2

field() {
  sed -n "s/^[[:space:]]*$1[[:space:]]*=[[:space:]]*\"\(.*\)\"[[:space:]]*$/\1/p" "$fragment" | head -n 1
}
cmd=$(field plugin_cmd)
sum=$(field plugin_checksum)
cas=$(field ca_path)
if [ -z "$cmd" ] || [ -z "$sum" ] || [ -z "$cas" ]; then
  echo "render-server-conf-patch: plugin_cmd, plugin_checksum or ca_path missing from $fragment" >&2
  exit 1
fi

conf=$(awk '
  /^# Source: .*spire-server\/templates\/configmap\.yaml$/ { in_cm = 1; next }
  in_cm && /^---/ { exit }
  in_cm && /^  server\.conf: \|/ { in_conf = 1; next }
  in_conf && /^    / { sub(/^    /, ""); print; next }
  in_conf { in_conf = 0 }
' "$rendered")
if [ -z "$conf" ]; then
  echo "render-server-conf-patch: no spire-server ConfigMap with a server.conf in $rendered" >&2
  exit 1
fi
printf '%s\n' "$conf" | jq -e '.plugins.NodeAttestor | length > 0' >/dev/null

cat <<EOF
# Generated by \`make kind-spire-render\` from $rendered and $fragment; do not edit.
# The chart's server.conf with the tpm node attestor of ADR-0018 added beside k8s_psat.
apiVersion: v1
kind: ConfigMap
metadata:
  name: spire-server
  namespace: spire-server
data:
  server.conf: |
EOF
printf '%s\n' "$conf" | jq --arg cmd "$cmd" --arg sum "$sum" --arg cas "$cas" \
  '.plugins.NodeAttestor += [{"tpm": {"plugin_cmd": $cmd, "plugin_checksum": $sum, "plugin_data": {"ca_path": $cas}}}]' \
  | sed 's/^/    /'
