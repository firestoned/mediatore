# The kind tier's server.conf, as a kustomize patch: the rendered ConfigMap's
# server.conf (one JSON key of one ConfigMap, so a patch replaces it whole) plus the
# `tpm` NodeAttestor block, read from deploy/spire-tpm/server.conf.fragment.hcl, and the
# `vault` UpstreamAuthority block (ADR-0031), read from
# deploy/spire-upstream/server.conf.fragment.hcl with its vault_addr replaced by the kind
# OpenBao Service's, so the components stay the single source of every path, checksum
# and role name. Run by `make kind-spire-render`; the output is tracked.
#
# Usage: render-server-conf-patch.sh <rendered spire.yaml> <tpm fragment> <upstream fragment> <kind vault_addr>
set -eu
rendered=$1
fragment=$2
upstream=$3
vault_addr=$4

field() {
  sed -n "s/^[[:space:]]*$2[[:space:]]*=[[:space:]]*\"\(.*\)\"[[:space:]]*$/\1/p" "$1" | head -n 1
}
cmd=$(field "$fragment" plugin_cmd)
sum=$(field "$fragment" plugin_checksum)
cas=$(field "$fragment" ca_path)
if [ -z "$cmd" ] || [ -z "$sum" ] || [ -z "$cas" ]; then
  echo "render-server-conf-patch: plugin_cmd, plugin_checksum or ca_path missing from $fragment" >&2
  exit 1
fi
mount=$(field "$upstream" pki_mount_point)
ca=$(field "$upstream" ca_cert_path)
kmount=$(field "$upstream" k8s_auth_mount_point)
role=$(field "$upstream" k8s_auth_role_name)
token=$(field "$upstream" token_path)
if [ -z "$mount" ] || [ -z "$ca" ] || [ -z "$kmount" ] || [ -z "$role" ] || [ -z "$token" ]; then
  echo "render-server-conf-patch: pki_mount_point, ca_cert_path, k8s_auth_mount_point, k8s_auth_role_name or token_path missing from $upstream" >&2
  exit 1
fi

conf=$(awk '
  /^# Source: .*spire-server\/templates\/configmap\.yaml$/ { in_cm = 1; next }
  in_cm && /^---/ { exit }
  in_cm && /^  server\.conf: \|/ { in_conf = 1; next }
  in_conf && /^    / { sub(/^    /, ""); print; next }
  in_conf { in_conf = 0 }
' "$rendered")
if [ -z "$conf" ]; then
  echo "render-server-conf-patch: no spire-server ConfigMap with a server.conf in $rendered" >&2
  exit 1
fi
printf '%s\n' "$conf" | jq -e '.plugins.NodeAttestor | length > 0' >/dev/null

cat <<EOF
# Generated by \`make kind-spire-render\` from $rendered, $fragment and $upstream; do not edit.
# The chart's server.conf with the tpm node attestor of ADR-0018 added beside k8s_psat and
# the vault upstream authority of ADR-0031 against the kind OpenBao.
apiVersion: v1
kind: ConfigMap
metadata:
  name: spire-server
  namespace: spire-server
data:
  server.conf: |
EOF
printf '%s\n' "$conf" | jq --arg cmd "$cmd" --arg sum "$sum" --arg cas "$cas" \
    --arg addr "$vault_addr" --arg mount "$mount" --arg ca "$ca" --arg kmount "$kmount" --arg role "$role" --arg token "$token" \
  '.plugins.NodeAttestor += [{"tpm": {"plugin_cmd": $cmd, "plugin_checksum": $sum, "plugin_data": {"ca_path": $cas}}}]
   | .plugins.UpstreamAuthority = [{"vault": {"plugin_data": {"vault_addr": $addr, "pki_mount_point": $mount, "ca_cert_path": $ca,
       "k8s_auth": {"k8s_auth_mount_point": $kmount, "k8s_auth_role_name": $role, "token_path": $token}}}}]' \
  | sed 's/^/    /'
