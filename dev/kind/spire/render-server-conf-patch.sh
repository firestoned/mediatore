# The kind tier's server.conf, as a kustomize patch: the rendered ConfigMap's
# server.conf (one JSON key of one ConfigMap, so a patch replaces it whole) plus the
# `tpm` NodeAttestor block, read from deploy/spire-tpm/server.conf.fragment.hcl, the
# `x509pop` NodeAttestor block (ADR-0049), read from
# deploy/spire-x509pop/server.conf.fragment.hcl, and the `vault` UpstreamAuthority block
# (ADR-0031), read from deploy/spire-upstream/server.conf.fragment.hcl with its vault_addr
# replaced by the kind OpenBao Service's, so the components stay the single source of
# every path, checksum, template and role name. Run by `make kind-spire-render`; the
# output is tracked.
#
# Usage: render-server-conf-patch.sh <rendered spire.yaml> <tpm fragment> <x509pop fragment> <upstream fragment> <kind vault_addr>
set -eu
rendered=$1
fragment=$2
x509pop=$3
upstream=$4
vault_addr=$5

# The first `key = "value"` line of a fragment, the value as written: everything between
# the first quote after the `=` and the last quote of the line, so a value holding braces
# and spaces (agent_path_template) comes through whole. The key is anchored at the start
# of the line: ca_path does not match ca_bundle_path.
field() {
  sed -n "s/^[[:space:]]*$2[[:space:]]*=[[:space:]]*\"\(.*\)\"[[:space:]]*$/\1/p" "$1" | head -n 1
}
cmd=$(field "$fragment" plugin_cmd)
sum=$(field "$fragment" plugin_checksum)
cas=$(field "$fragment" ca_path)
if [ -z "$cmd" ] || [ -z "$sum" ] || [ -z "$cas" ]; then
  echo "render-server-conf-patch: plugin_cmd, plugin_checksum or ca_path missing from $fragment" >&2
  exit 1
fi
bundle=$(field "$x509pop" ca_bundle_path)
template=$(field "$x509pop" agent_path_template)
if [ -z "$bundle" ] || [ -z "$template" ]; then
  echo "render-server-conf-patch: ca_bundle_path or agent_path_template missing from $x509pop" >&2
  exit 1
fi
# ADR-0049 decision 2: the issuer-qualified template and no other. A fragment edited to
# the CN-only or the fingerprint form must not reach a tier that would then prove it.
if [ "$template" != '/x509pop/{{ .Issuer.CommonName }}/{{ .Subject.CommonName }}' ]; then
  echo "render-server-conf-patch: agent_path_template in $x509pop is not the template of ADR-0049 decision 2: $template" >&2
  exit 1
fi
mount=$(field "$upstream" pki_mount_point)
ca=$(field "$upstream" ca_cert_path)
kmount=$(field "$upstream" k8s_auth_mount_point)
role=$(field "$upstream" k8s_auth_role_name)
token=$(field "$upstream" token_path)
if [ -z "$mount" ] || [ -z "$ca" ] || [ -z "$kmount" ] || [ -z "$role" ] || [ -z "$token" ]; then
  echo "render-server-conf-patch: pki_mount_point, ca_cert_path, k8s_auth_mount_point, k8s_auth_role_name or token_path missing from $upstream" >&2
  exit 1
fi

conf=$(awk '
  /^# Source: .*spire-server\/templates\/configmap\.yaml$/ { in_cm = 1; next }
  in_cm && /^---/ { exit }
  in_cm && /^  server\.conf: \|/ { in_conf = 1; next }
  in_conf && /^    / { sub(/^    /, ""); print; next }
  in_conf { in_conf = 0 }
' "$rendered")
if [ -z "$conf" ]; then
  echo "render-server-conf-patch: no spire-server ConfigMap with a server.conf in $rendered" >&2
  exit 1
fi
printf '%s\n' "$conf" | jq -e '.plugins.NodeAttestor | length > 0' >/dev/null

cat <<EOF
# Generated by \`make kind-spire-render\` from $rendered, $fragment, $x509pop and $upstream; do not edit.
# The chart's server.conf with the tpm node attestor of ADR-0018 and the x509pop node attestor of
# ADR-0049 added beside k8s_psat, and the vault upstream authority of ADR-0031 against the kind OpenBao.
apiVersion: v1
kind: ConfigMap
metadata:
  name: spire-server
  namespace: spire-server
data:
  server.conf: |
EOF
printf '%s\n' "$conf" | jq --arg cmd "$cmd" --arg sum "$sum" --arg cas "$cas" --arg bundle "$bundle" --arg template "$template" \
    --arg addr "$vault_addr" --arg mount "$mount" --arg ca "$ca" --arg kmount "$kmount" --arg role "$role" --arg token "$token" \
  '.plugins.NodeAttestor += [{"tpm": {"plugin_cmd": $cmd, "plugin_checksum": $sum, "plugin_data": {"ca_path": $cas}}},
       {"x509pop": {"plugin_data": {"ca_bundle_path": $bundle, "agent_path_template": $template}}}]
   | .plugins.UpstreamAuthority = [{"vault": {"plugin_data": {"vault_addr": $addr, "pki_mount_point": $mount, "ca_cert_path": $ca,
       "k8s_auth": {"k8s_auth_mount_point": $kmount, "k8s_auth_role_name": $role, "token_path": $token}}}}]' \
  | sed 's/^/    /'
